void write_number(int n)
{
    char buf[12];
    int i = 0;
    if (n == 0) { WriteUart('0'); return; }
    while (n > 0) { buf[i++] = '0' + n % 10; n /= 10; }
    while (i > 0) WriteUart(buf[--i]);
}

void play()
{
    ClearScreen();
    // HINT: This is the main game loop
    draw_playing_field();
    while (1)
    {
        update_game_state();
        update_bar_state();
        if (currentState != Running)
        {
            break;
        }
        draw_ball_color(black);
        draw_bar(bar.pos_y); // TODO: replace the constant value with the current position of the bar
        delay(FRAME_DELAY); // Used to slow down ball
    }
    
    if (currentState == Won)
    {
        write(won);
        write(" - Paddle moves: ");
        write_number(paddle_moves);
        WriteUart('\n');
    }
    else if (currentState == Lost)
    {
        write(lost);
        write(" - Blocks destroyed: ");
        write_number(blocks_destroyed);
        WriteUart('\n');
    }
    else if (currentState == Exit)
    {
        return;
    }
    currentState = Stopped;
}

// It must initialize the game

void reset()
{
    // Hint: This is draining the UART buffer
    int remaining = 0;
    int row;
    int col;
    do
    {
        unsigned long long out = ReadUart();
        if (!(out & 0x8000))
        {
            break;
        }
        remaining = (out & 0xFF0000) >> 4;
    } while (remaining > 0);
    currentState = Running;
    ball = (Ball){100, 100, BASE_VELOCITY, 0};
    bar.pos_y = 100;
    for (row = 0; row < NROWS; row++)
        for (col = 0; col < NCOLS; col++)
            tiles[row][col] = 0;
    // TODO: You might want to reset other state in here
    blocks_destroyed = 0;
    paddle_moves = 0;
}


void wait_for_start()
{
    while (1) {
        int input = ReadUart();
        if (!(input & 0x8000)) {
            continue;               
        }
        char c = input & 0xFF;
        if (c == '\n' || c == '\r') {
            currentState = Exit;        
            return;
        }
        if (c == 'w' || c == 's') {
            currentState = Running;     
            return;
        }
    }
}

int main(int argc, char *argv[])
{
    ClearScreen();

    // HINT: This loop allows the user to restart the game after loosing/winning the previous game
    while (1)
    {
        wait_for_start();
        if(currentState == Exit){
            break;
        }
        play();
        if (currentState == Exit)
        {
            break;
        }
        reset();
    }
    return 0;
}

